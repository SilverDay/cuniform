<?php

declare(strict_types=1);

namespace Cuniform\Tests\Build;

use Cuniform\Build\RedirectEntry;
use Cuniform\Build\RedirectMapGenerator;
use PHPUnit\Framework\TestCase;

final class RedirectMapGeneratorTest extends TestCase
{
    public function testFormatsEntriesAsRedirectMatchDirectivesWithAbsoluteTargets(): void
    {
        $entries = [new RedirectEntry('/feed.xml', '/de/feed.xml', 'content/redirects.map')];

        $file = (new RedirectMapGenerator(ConfigFixture::make()))->generate($entries);

        self::assertSame('redirects.conf', $file->relativePath);
        self::assertStringContainsString(
            'RedirectMatch 301 ^/feed\.xml$ https://blog.silverday.de/de/feed.xml',
            $file->contents
        );
    }

    public function testEscapesRegexMetacharactersInTheOldPath(): void
    {
        $entries = [new RedirectEntry('/a.b+c/', '/x/', 'test')];

        $file = (new RedirectMapGenerator(ConfigFixture::make()))->generate($entries);

        self::assertStringContainsString('^/a\.b\+c/$', $file->contents);
    }

    public function testEmptyEntriesStillProducesAValidHeaderOnlyFile(): void
    {
        $file = (new RedirectMapGenerator(ConfigFixture::make()))->generate([]);

        self::assertStringContainsString('Generated by Cuniform', $file->contents);
        self::assertStringNotContainsString('RedirectMatch', $file->contents);
    }
}
