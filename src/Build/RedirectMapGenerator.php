<?php

declare(strict_types=1);

namespace Cuniform\Build;

use Cuniform\Config\Config;

/**
 * Compiles a redirect set into a `RedirectMatch 301` block (SPEC §8.3 offers
 * this or a `RewriteMap txt:` file; a self-contained block needs no
 * companion map file, so it's the simpler of the two to actually wire into
 * a vhost later, T27). Targets are absolute URLs — a 301 to a relative path
 * works too, but an absolute target is unambiguous regardless of how the
 * directive ends up included.
 *
 * The compiled file itself only ever lands inside a release tree
 * (BuildPipeline writes it like any other artifact); actually `Include`-ing
 * it from the vhost config, and reloading Apache so a new one takes effect,
 * is T27's job, not this one's.
 */
final class RedirectMapGenerator
{
    public function __construct(private readonly Config $config)
    {
    }

    /**
     * @param list<RedirectEntry> $entries
     */
    public function generate(array $entries): ArtifactFile
    {
        $lines = [
            '# Generated by Cuniform — do not edit; edit content/redirects.map instead (SPEC §8.3)',
        ];

        foreach ($entries as $entry) {
            $pattern = '^' . preg_quote($entry->oldPath) . '$';
            $target  = rtrim($this->config->baseUrl, '/') . $entry->newPath;
            $lines[] = "RedirectMatch 301 {$pattern} {$target}";
        }

        return new ArtifactFile('redirects.conf', implode("\n", $lines) . "\n");
    }
}
